function слово(документ, позиция) {
  const текст = документ.getText().split('\n')[позиция.line] || '';
  for (const м of текст.matchAll(new RegExp(ИДЕНТ, 'gu'))) {
    if (м.index <= позиция.character && позиция.character <= м.index + м[0].length) return м[0];
  }
  return null;
}

// Номер строки процедуры, внутри которой находится строка документа.
function областьСтроки(объявления, строка) {
  const процедуры = объявления.filter(о => о.вид === 'про' && о.строка <= строка);
  const последняя = процедуры.length ? процедуры[процедуры.length - 1] : null;
  // Структура или константа после процедуры заканчивает её тело, но на практике
  // «про» идут подряд, поэтому границей считаем только следующую «про».
  return последняя ? последняя.строка : null;
}

// Локальные имена, видимые в позиции: параметры и переменные текущей процедуры, объявленные выше курсора,
// и глобальные объявления файла.
function видимыеЛокальные(локальные, позиция) {
  const область = областьСтроки(локальные, позиция.line);
  return локальные.filter(о => о.вид !== 'поле' && (о.глобальное
    || (область !== null && о.область === область && о.строка <= позиция.line)));
}

// Ближайшее объявление: локальное выше курсора, затем глобальное этого файла, затем из включённых.
function найтиОбъявление(документ, позиция, имя) {
  const { локальные, внешние } = объявленияДоступные(документ);
  const видимые = видимыеЛокальные(локальные, позиция).filter(о => о.имя === имя);
  const ближайшая = видимые.filter(о => !о.глобальное).pop();
  return ближайшая || видимые.find(о => о.глобальное) || внешние.find(о => о.имя === имя && о.вид !== 'поле');
}

function документация(о) {
  const код = '```cuya\n' + о.подпись + '\n```';
  const части = [код];
  if (о.док) части.push(о.док);
  if (о.модуль) части.push(`_модуль «${о.модуль}»_`);
  return { kind: MarkupKind.Markdown, value: части.join('\n\n') };
}

// Имя структуры в типе: «Вектор2» -> «Вектор2», «массив(10, Вектор2)» -> null.
const имяСтруктуры = тип => (new RegExp(`^${ИДЕНТ}$`, 'u').test(тип || '') ? тип : null);

// Где вставить «вкл имя;»: после последнего «вкл» либо в начало файла.
function правкаВключения(документ, имя) {
  const строки = документ.getText().split('\n');
  let последняя = -1;
  строки.forEach((с, н) => { if (РЕ_ВКЛ.test(с)) последняя = н; });
  if (последняя >= 0) {
    return { range: { start: { line: последняя + 1, character: 0 }, end: { line: последняя + 1, character: 0 } }, newText: `вкл ${имя};\n` };
  }
  return { range: { start: { line: 0, character: 0 }, end: { line: 0, character: 0 } }, newText: `вкл ${имя};\n\n` };
}

function элементДополнения(о, документ, нужноВключение) {
  const элемент = {
    label: о.имя, kind: ВИД_ДОПОЛНЕНИЯ[о.вид], detail: о.подпись,
    documentation: документация(о),
  };
  if (о.вид === 'про' && о.параметры) {
    // Скобки и поля для аргументов; без параметров — просто «()».
    элемент.insertTextFormat = InsertTextFormat.Snippet;
    элемент.insertText = о.параметры.length ? `${о.имя}($0)` : `${о.имя}()$0`;
  }
  if (нужноВключение) {
    элемент.detail = `${о.подпись}  — из «${о.модуль}»`;
    элемент.additionalTextEdits = [правкаВключения(документ, о.модуль)];
    элемент.sortText = 'я' + о.имя; // выше показываем то, что уже доступно
  }
  return элемент;
}

соединение.onCompletion(({ textDocument, position }) => {
  const документ = документы.get(textDocument.uri);
  if (!документ) return [];
  const { локальные, внешние, доступные } = объявленияДоступные(документ);
  const доКурсора = (документ.getText().split('\n')[position.line] || '').slice(0, position.character);

  // «вкл »: предлагаем модули.
  if (new RegExp('^[ \\t]*вкл[ \\t]+[\\p{L}\\p{N}_]*$', 'u').test(доКурсора)) {
    const cwd = папкаЗапуска(fileURLToPath(документ.uri));
    return списокМодулей(cwd).map(label => ({ label, kind: CompletionItemKind.Module }));
  }

  const уникальные = (список, фабрика) => {
    const видны = new Set();
    return список.filter(о => !видны.has(о.имя) && видны.add(о.имя)).map(фабрика);
  };

  // После точки: поля. Если слева имя переменной со структурным типом — только её поля.
  const точка = new RegExp(`(${ИДЕНТ})?\\.$`, 'u').exec(доКурсора);
  if (точка && !доКурсора.endsWith('..')) {
    const переменная = точка[1] && видимыеЛокальные(локальные, position).concat(внешние)
      .filter(о => о.имя === точка[1] && о.вид === 'пер').pop();
    const структура = переменная && имяСтруктуры(переменная.тип);
    const поля = [...локальные, ...внешние].filter(о => о.вид === 'поле' && (!структура || о.структура === структура));
    return уникальные(поля, о => ({ label: о.имя, kind: CompletionItemKind.Field, detail: о.подпись + (структура ? '' : `  — в «${о.структура}»`),
      documentation: о.док || undefined }));
  }

  const типы = () => [
    ...ТИПЫ.map(([label, documentation]) => ({ label, kind: CompletionItemKind.Class, documentation })),
    ...ПАРАМЕТРИЗИРОВАННЫЕ_ТИПЫ.map(([label, detail, insertText, documentation]) => ({
      label, detail, documentation, kind: CompletionItemKind.Class, insertText, insertTextFormat: InsertTextFormat.Snippet })),
    ...уникальные([...локальные, ...внешние].filter(о => о.вид === 'структ'), о => элементДополнения(о, документ, false)),
    ...уникальные(доступные.filter(о => о.вид === 'структ'), о => элементДополнения(о, документ, true)),
  ];

  // После «:» или «как»: только типы.
  if (new RegExp('(?:[^:]:|\\)[ \\t]*:|(?<![\\p{L}\\p{N}_])как)[ \\t]*[\\p{L}\\p{N}_]*$', 'u').test(доКурсора)) return типы();

  const видимые = видимыеЛокальные(локальные, position);
  const известные = new Set([...видимые, ...внешние].map(о => о.имя));
  return [
    ...КЛЮЧЕВЫЕ_СЛОВА.filter(label => !СЛОВА_ШАБЛОНОВ.has(label)).map(label => ({ label, kind: CompletionItemKind.Keyword })),
    ...ШАБЛОНЫ.map(([label, detail, insertText]) => ({
      label, detail, insertText, insertTextFormat: InsertTextFormat.Snippet, kind: CompletionItemKind.Snippet,
      sortText: label + '~' })),
    ...типы(),
    ...ВСТРОЕННЫЕ.map(в => ({
      label: в.имя, kind: CompletionItemKind.Function, detail: в.подпись,
      documentation: { kind: MarkupKind.Markdown, value: в.док },
      insertText: `${в.имя}($0)`, insertTextFormat: InsertTextFormat.Snippet })),
    ...уникальные([...видимые, ...внешние].filter(о => о.вид !== 'поле'), о => элементДополнения(о, документ, false)),
    ...уникальные(доступные.filter(о => !известные.has(о.имя)), о => элементДополнения(о, документ, true)),
  ];
});

соединение.onDefinition(({ textDocument, position }) => {
  const документ = документы.get(textDocument.uri);
  const имя = документ && слово(документ, position);
  const о = имя && найтиОбъявление(документ, position, имя);
  if (!о) return null;
  const range = { start: { line: о.строка, character: о.столбец }, end: { line: о.строка, character: о.столбец + о.имя.length } };
  return { uri: о.uri, range };
});

соединение.onHover(({ textDocument, position }) => {
  const документ = документы.get(textDocument.uri);
  const имя = документ && слово(документ, position);
  if (!имя) return null;
  const о = найтиОбъявление(документ, position, имя);
  if (о) return { contents: документация(о) };
  const встроенная = ВСТРОЕННЫЕ.find(в => в.имя === имя);
  if (встроенная) {
    return { contents: { kind: MarkupKind.Markdown, value: '```cuya\n' + встроенная.подпись + '\n```\n\n' + встроенная.док } };
  }
  const тип = ТИПЫ.find(([т]) => т === имя);
  return тип ? { contents: { kind: MarkupKind.Markdown, value: '```cuya\n' + имя + '\n```\n\n' + тип[1] } } : null;
});

// Подсказка параметров при вызове: находим незакрытую «(» слева от курсора.
соединение.onSignatureHelp(({ textDocument, position }) => {
  const документ = документы.get(textDocument.uri);
  if (!документ) return null;
  const строка = (документ.getText().split('\n')[position.line] || '').slice(0, position.character);
  const стек = [];
  let внутриСтроки = false;
  for (let к = 0; к < строка.length; к++) {
    const с = строка[к];
    if (с === '«') внутриСтроки = true;
    else if (с === '»') внутриСтроки = false;
    else if (внутриСтроки) continue;
    else if (с === '(') стек.push({ позиция: к, запятые: 0 });
    else if (с === ')') стек.pop();
    else if (с === ',' && стек.length) стек[стек.length - 1].запятые++;
  }
  const скобка = стек.pop();
  if (!скобка) return null;
  const имя = new RegExp(`(${ИДЕНТ})[ \\t]*$`, 'u').exec(строка.slice(0, скобка.позиция));
  if (!имя) return null;
  const о = найтиОбъявление(документ, position, имя[1]);
  const встроенная = !о && ВСТРОЕННЫЕ.find(в => в.имя === имя[1]);
  const источник = о && о.вид === 'про' ? { подпись: о.подпись, параметры: о.параметры, док: о.док }
    : встроенная ? встроенная : null;
  if (!источник) return null;
  return {
    signatures: [{
      label: источник.подпись,
      documentation: источник.док ? { kind: MarkupKind.Markdown, value: источник.док } : undefined,
      parameters: источник.параметры.map(label => ({ label })),
    }],
    activeSignature: 0,
    activeParameter: Math.min(скобка.запятые, Math.max(0, источник.параметры.length - 1)),
  };
});

